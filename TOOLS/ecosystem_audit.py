"""Fast full-ecosystem audit: classify every .py under 06_SOURCE_CODE.
Uses compile() (C-speed) for syntax + a line-based heuristic for stubs.
Writes ECOSYSTEM_AUDIT.md and ECOSYSTEM_AUDIT_RAW.txt."""
import os
import sys
from collections import defaultdict

ROOT = r"C:\Users\navid\Desktop\AURA\06_SOURCE_CODE"
OUT = r"C:\Users\navid\Desktop\AURA\ECOSYSTEM_AUDIT.md"
RAW = r"C:\Users\navid\Desktop\AURA\ECOSYSTEM_AUDIT_RAW.txt"

SKIP = {".venv", "site-packages", "node_modules", "__pycache__", ".git",
        ".tox", ".mypy_cache", ".ruff_cache", ".pytest_cache", "dist", "build",
        "eggs", ".egg-info"}


def walk_py(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP]
        for fn in filenames:
            if fn.endswith(".py"):
                yield os.path.join(dirpath, fn)


def classify_text(text):
    """EMPTY / BROKEN / STUB / REAL via a fast line heuristic."""
    stripped = text.strip()
    if not stripped:
        return "EMPTY"
    try:
        compile(text, "<src>", "exec")
    except SyntaxError:
        return "BROKEN"
    code = 0
    defs = 0
    pass_lines = 0
    strings = 0
    for ln in text.splitlines():
        s = ln.strip()
        if not s:
            continue
        if s.startswith("#"):
            continue
        if s.startswith(("\"\"\"", "'''", "r'''", "r\"\"\"")):
            strings += 1
            continue
        if s.startswith(("def ", "class ", "async def ")):
            defs += 1
            code += 1
            continue
        if s in ("pass", "..."):
            pass_lines += 1
            continue
        code += 1
    if strings and code == 0 and defs == 0:
        return "STUB"
    if code <= 2 and defs <= 1:
        return "STUB" if pass_lines >= max(1, code) else "REAL"
    if pass_lines > code and code < 4:
        return "STUB"
    if code == 0:
        return "STUB"
    return "REAL"


def audit_repo(root):
    py_files = list(walk_py(root))
    counts = defaultdict(int)
    broken, empty, stub, tests = [], [], [], []
    for path in py_files:
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError:
            text = ""
        cls = classify_text(text)
        counts[cls] += 1
        rel = path.replace(ROOT + os.sep, "").replace("\\", "/")
        if cls == "BROKEN":
            broken.append(rel)
        elif cls == "EMPTY":
            empty.append(rel)
        elif cls == "STUB":
            stub.append(rel)
        low = os.path.basename(path).lower()
        parent = os.path.basename(os.path.dirname(path)).lower()
        if "test" in low or "test" in parent:
            tests.append(rel)
    zero = sum(1 for p in py_files if os.path.getsize(p) == 0)
    return {"repo": os.path.basename(root), "py_files": len(py_files),
            "real": counts["REAL"], "stub": counts["STUB"], "empty": counts["EMPTY"],
            "broken": counts["BROKEN"], "zero": zero, "tests": len(tests),
            "broken_list": broken[:40]}


def status_for(r):
    if r["py_files"] == 0:
        return "EMPTY-DIR"
    if r["broken"]:
        return "BROKEN"
    ratio = r["real"] / r["py_files"]
    if ratio >= 0.5 and r["real"] >= 5:
        return "STRONG" if r["tests"] > 0 else "REAL-UNTESTED"
    if ratio >= 0.2 or r["real"] >= 3:
        return "PARTIAL"
    return "SCAFFOLD"


def main():
    rows = []
    for d in sorted(os.listdir(ROOT)):
        full = os.path.join(ROOT, d)
        if not os.path.isdir(full) or d in SKIP:
            continue
        r = audit_repo(full)
        r["status"] = status_for(r)
        rows.append(r)
    rows.sort(key=lambda x: x["repo"])
    lines = ["# ECOSYSTEM AUDIT", "",
             "Auto-generated by `TOOLS/ecosystem_audit.py`. Every `.py` under `06_SOURCE_CODE/`",
             "is classified REAL / STUB / EMPTY / BROKEN based on actual content.", "",
             "| Repository | Py | Real | Stub | Empty | Broken | ZeroB | TestFiles | Status |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['repo']} | {r['py_files']} | {r['real']} | {r['stub']} | {r['empty']} "
                     f"| {r['broken']} | {r['zero']} | {r['tests']} | {r['status']} |")
    t = f"| **TOTAL** | **{sum(r['py_files'] for r in rows)}** | **{sum(r['real'] for r in rows)}** | " \
        f"**{sum(r['stub'] for r in rows)}** | **{sum(r['empty'] for r in rows)}** | " \
        f"**{sum(r['broken'] for r in rows)}** | **{sum(r['zero'] for r in rows)}** | " \
        f"**{sum(r['tests'] for r in rows)}** | |"
    lines.append(t)
    lines += ["", "## Repositories with broken files"]
    any_broken = False
    for r in rows:
        if r["broken"]:
            any_broken = True
            lines.append(f"\n### {r['repo']} ({r['broken']} broken)")
            for b in r["broken_list"][:25]:
                lines.append(f"- `{b}`")
    if not any_broken:
        lines.append("\nNone.")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(RAW, "w", encoding="utf-8") as fh:
        fh.write("Repository\tPy\tReal\tStub\tEmpty\tBroken\tZeroB\tTests\tStatus\n")
        for r in rows:
            fh.write(f"{r['repo']}\t{r['py_files']}\t{r['real']}\t{r['stub']}\t{r['empty']}\t"
                     f"{r['broken']}\t{r['zero']}\t{r['tests']}\t{r['status']}\n")
    print(f"Wrote {os.path.basename(OUT)} and {os.path.basename(RAW)}")
    for r in rows:
        print(f"{r['repo']:<26} py={r['py_files']:>6} real={r['real']:>5} stub={r['stub']:>5} "
              f"empty={r['empty']:>5} broken={r['broken']:>5} tests={r['tests']:>4}  {r['status']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
