"""AURA persistent in-memory scheduling store abstraction."""
from __future__ import annotations
import threading,time
from copy import deepcopy

class StoreError(Exception):pass
class NotFoundError(StoreError):pass
class Store:
    def __init__(self):
        self._data={};self._lock=threading.RLock()
    def put(self,key,value):
        with self._lock:self._data[str(key)]=deepcopy(value)
        return value
    def get(self,key,default=None):
        with self._lock:return deepcopy(self._data.get(str(key),default))
    def require(self,key):
        value=self.get(key)
        if value is None:raise NotFoundError(str(key))
        return value
    def delete(self,key):
        with self._lock:return self._data.pop(str(key),None)
    def exists(self,key):
        with self._lock:return str(key) in self._data
    def keys(self):
        with self._lock:return list(self._data)
    def values(self):
        with self._lock:return [deepcopy(v) for v in self._data.values()]
    def items(self):
        with self._lock:return [(k,deepcopy(v)) for k,v in self._data.items()]
    def count(self):return len(self._data)
    def clear(self):
        with self._lock:self._data.clear()
    def snapshot(self):
        return {"count":self.count(),"keys":self.keys(),"created_at":getattr(self,"created_at",None)}
    def health(self):return True
class TaskStore(Store):
    def save_task(self,task):return self.put(task.task_id,task.snapshot())
    def load_task(self,task_id):return self.require(task_id)
    def remove_task(self,task_id):return self.delete(task_id)
class ResultStore(Store):
    def save_result(self,result):return self.put(result.task_id,result.snapshot())
    def load_result(self,task_id):return self.require(task_id)
class ScheduleStore(Store):
    def save_schedule(self,name,data):return self.put(name,data)
    def load_schedule(self,name):return self.require(name)
task_store=TaskStore();result_store=ResultStore();schedule_store=ScheduleStore()
class StorePolicy1:
    """Operational scheduling policy 1."""
    name="store_policy_1"
    priority=1
    timeout=2.1
    retries=1
    enabled=True
    def __init__(self,**options):
        self.options={"priority":self.priority,"timeout":self.timeout,
                       "retries":self.retries,"enabled":self.enabled}
        self.options.update(options)
    def configure(self,**options):
        self.options.update(options)
        return self
    def enable(self):
        self.options["enabled"]=True
        return self
    def disable(self):
        self.options["enabled"]=False
        return self
    def is_enabled(self):
        return bool(self.options.get("enabled",True))
    def retry_allowed(self,attempt):
        return self.is_enabled() and int(attempt)<int(self.options.get("retries",0))
    def delay(self,attempt):
        return min(float(self.options.get("timeout",1)), max(0,float(attempt))*0.1)
    def snapshot(self):
        return {"name":self.name,"options":dict(self.options)}
    def health(self):
        return self.is_enabled() and float(self.options.get("timeout",1))>0
