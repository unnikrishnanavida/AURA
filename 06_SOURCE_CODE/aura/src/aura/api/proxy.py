"""TLS-terminating reverse proxy for production-like AURA deployments.

Minimal, real reverse proxy built on the standard library:

- **TLS termination** on the HTTPS port (cert/key supplied by the operator or
  a local test CA generated by a dev helper; never generated in this module).
- **HTTP → HTTPS redirect** on an optional plain-HTTP port.
- **Round-robin + failover** across a configured list of upstream AURA API
  instances (an unreachable upstream falls through to the next healthy one).
- **Trusted proxy forwarding**: the proxy sets ``X-Forwarded-For`` from the
  real client IP and ``X-Forwarded-Proto``. API instances configured with
  ``trust_proxy=True`` honor XFF only from this proxy; they must not be
  directly reachable from untrusted networks.

The proxy is stateless; cross-instance consistency is provided by the shared
PostgreSQL state, never by the proxy.
"""

from __future__ import annotations

import http.client
import http.server
import ssl
import threading
import time
from dataclasses import dataclass, field
from typing import Any, cast

from aura.foundation.errors import ConfigurationError


@dataclass
class Upstream:
    host: str
    port: int
    weight: int = 1


@dataclass
class ProxyConfig:
    """Validation-free flat configuration consumed directly by :class:`TLSProxy`."""

    host: str = "127.0.0.1"
    tls_port: int = 8443
    redirect_port: int | None = 8080
    tls_certfile: str = ""
    tls_keyfile: str = ""
    upstreams: list[Upstream] = field(default_factory=list)
    max_request_bytes: int = 1_048_576
    timeout_seconds: float = 10.0
_SECURITY_HEADERS = {
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "no-referrer",
}


class _ProxyHandler(http.server.BaseHTTPRequestHandler):
    """Forward requests to a healthy upstream with failover + headers."""

    server_version = "AURA-Proxy/1.0"

    def log_message(self, fmt: str, *args: Any) -> None:  # noqa: A002
        return

    @property
    def _proxy(self) -> TLSProxy:
        server: Any = self.server
        return cast(TLSProxy, server.proxy)

    def _forward_request(self) -> None:
        length = int(self.headers.get("Content-Length", "0") or 0)
        proxy = self._proxy
        if length > proxy.config.max_request_bytes:
            self._error(413, "request body too large")
            return
        body = self.rfile.read(length) if length > 0 else None

        client_ip = self.client_address[0] if self.client_address else "unknown"
        upstreams = list(proxy.config.upstreams)
        start = getattr(proxy, "_rr", 0)
        status = None
        for offset in range(len(upstreams)):
            upstream = upstreams[(start + offset) % len(upstreams)]
            status, headers, payload = proxy._forward(
                upstream,
                command=self.command,
                path=self.path,
                headers=self.headers,
                body=body,
                client_ip=client_ip,
            )
            if status is not None:
                break
        if status is None:
            self._error(502, "no healthy upstream available")
            return

        self.send_response(status)
        for key, value in headers.items():
            if key.lower() in {"transfer-encoding", "connection", "content-length", "x-forwarded-for"}:
                continue
            self.send_header(key, value)
        self.send_header("Content-Length", str(len(payload)))
        for key, value in _SECURITY_HEADERS.items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(payload)
        proxy._rr = (start + 1) % len(upstreams)

    def _error(self, status: int, message: str) -> None:
        import json

        payload = json.dumps({"error": {"code": "proxy.error", "message": message}}).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        for key, value in _SECURITY_HEADERS.items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(payload)

    def do_GET(self) -> None:  # noqa: N802
        self._forward_request()

    def do_POST(self) -> None:  # noqa: N802
        self._forward_request()

    def do_PUT(self) -> None:  # noqa: N802
        self._forward_request()

    def do_DELETE(self) -> None:  # noqa: N802
        self._forward_request()
class _RedirectHandler(http.server.BaseHTTPRequestHandler):
    """Redirect all plain-HTTP traffic to the HTTPS port."""

    def log_message(self, fmt: str, *args: Any) -> None:  # noqa: A002
        return

    def _redirect(self) -> None:
        target = f"https://{self.headers.get('Host', 'localhost')}{self.path}"
        self.send_response(301)
        self.send_header("Location", target)
        self.send_header("Content-Length", "0")
        self.end_headers()

    do_GET = _redirect
    do_POST = _redirect
    do_PUT = _redirect
    do_DELETE = _redirect


class TLSProxy:
    """Minimal TLS-terminating reverse proxy (TLS + HTTP->HTTPS + failover)."""

    def __init__(self, *, config: ProxyConfig) -> None:
        if not config.tls_certfile or not config.tls_keyfile:
            raise ConfigurationError("TLS proxy requires tls_certfile and tls_keyfile")
        if not config.upstreams:
            raise ConfigurationError("TLSProxy requires at least one upstream")
        self.config = config
        self._failures: dict[tuple[str, int], float] = {}
        self._rr = 0
        self._httpd: http.server.ThreadingHTTPServer | None = None
        self._redirect_httpd: http.server.ThreadingHTTPServer | None = None

    def _forward(
        self,
        upstream: Upstream,
        *,
        command: str,
        path: str,
        headers: Any,
        body: bytes | None,
        client_ip: str,
    ) -> tuple[int | None, dict[str, str], bytes]:
        try:
            conn = http.client.HTTPConnection(upstream.host, upstream.port, timeout=self.config.timeout_seconds)
            out_headers = {
                k: v for k, v in headers.items() if k.lower() not in {"host", "content-length", "connection"}
            }
            # The proxy is the trusted forwarder; it overwrites XFF so the API
            # never trusts a client-supplied forwarded header.
            out_headers["X-Forwarded-For"] = client_ip
            out_headers["X-Forwarded-Proto"] = "https"
            conn.request(command, path, body=body or b"", headers=out_headers)
        except Exception:  # noqa: BLE001
            self._failures[(upstream.host, upstream.port)] = time.time()
            return None, {}, b""
        try:
            resp = conn.getresponse()
            data = resp.read()
            if (upstream.host, upstream.port) in self._failures:
                del self._failures[(upstream.host, upstream.port)]
            return resp.status, dict(resp.getheaders()), data
        except Exception:  # noqa: BLE001
            self._failures[(upstream.host, upstream.port)] = time.time()
            return None, {}, b""
        finally:
            conn.close()

    def start(self) -> None:
        """Bind TLS (and redirect) servers; non-blocking."""
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        ctx.load_cert_chain(self.config.tls_certfile, self.config.tls_keyfile)

        self._httpd = http.server.ThreadingHTTPServer((self.config.host, self.config.tls_port), _ProxyHandler)
        self._httpd.proxy = self  # type: ignore[attr-defined]
        self._httpd.socket = ctx.wrap_socket(self._httpd.socket, server_side=True)
        threading.Thread(target=self._httpd.serve_forever, daemon=True).start()

        if self.config.redirect_port is not None:
            self._redirect_httpd = http.server.ThreadingHTTPServer(
                (self.config.host, self.config.redirect_port), _RedirectHandler
            )
            threading.Thread(target=self._redirect_httpd.serve_forever, daemon=True).start()

    def stop(self) -> None:
        for httpd in (self._httpd, self._redirect_httpd):
            if httpd is not None:
                httpd.shutdown()
                httpd.server_close()

    @property
    def tls_port(self) -> int:
        return self._httpd.server_port if self._httpd is not None else self.config.tls_port

    @property
    def redirect_port(self) -> int:
        return self._redirect_httpd.server_port if self._redirect_httpd is not None else -1


__all__ = ["ProxyConfig", "TLSProxy", "Upstream"]